// 契約要點（摘要，定稿以該文件為準）：
// - 錯誤碼格式為 `ETHER_<領域>_<具體錯誤>`，全大寫英文字母、數字、底線組成。
// - 錯誤回應頂層鍵為 `error`，須含 `code`、`message`、`request_id`。
// - 客戶端一律以錯誤碼（code）判讀，不得以訊息文字判讀；未知錯誤碼按通用伺服器錯誤處理。
// - 401 時僅嘗試刷新 Token 一次，刷新失敗則導向重新登入，不得無限重試。
// - 403 不重試；404 不得以有無推斷資源存在性或封鎖關係。
// - 可重試與不可重試的錯誤區分、重試次數與退避間隔，皆待定稿，不得預寫數字。
// - 錯誤訊息不得含密碼、Token、金鑰、E2EE 明文等敏感資訊。
// - WebSocket 錯誤以 docs/api/WEBSOCKET_PROTOCOL.md 為準，不得直接套用 HTTP 錯誤格式。
